#!/usr/bin/env python3
from pathlib import Path

ROM_SIZE=32768
rom=bytearray(ROM_SIZE)
logo=bytes([
0xCE,0xED,0x66,0x66,0xCC,0x0D,0x00,0x0B,0x03,0x73,0x00,0x83,0x00,0x0C,0x00,0x0D,
0x00,0x08,0x11,0x1F,0x88,0x89,0x00,0x0E,0xDC,0xCC,0x6E,0xE6,0xDD,0xDD,0xD9,0x99,
0xBB,0xBB,0x67,0x63,0x6E,0x0E,0xEC,0xCC,0xDD,0xDC,0x99,0x9F,0xBB,0xB9,0x33,0x3E])
rom[0x100:0x104]=bytes([0x00,0xC3,0x50,0x01])
rom[0x104:0x134]=logo
rom[0x134:0x13F]=b"IRQVBLANK\0\0"
rom[0x143]=0
rom[0x147]=0
rom[0x148]=0
rom[0x149]=0

# VBlank vector $0040, exactly 8 bytes: counter++ ; RETI
rom[0x40:0x48]=bytes([
    0xFA,0x00,0xC0,  # LD A,($C000)
    0x3C,            # INC A
    0xEA,0x00,0xC0,  # LD ($C000),A
    0xD9             # RETI
])
for vec in [0x48,0x50,0x58,0x60]: rom[vec]=0xD9
for vec in [0x00,0x08,0x10,0x18,0x20,0x28,0x30,0x38]: rom[vec]=0xC9

# Main:
# SP=FFFE; DI; counter=0; LCD on; IF=0; IE=1; EI; NOP; HALT; JP HALT
code=bytes([
    0x31,0xFE,0xFF,
    0xF3,
    0x3E,0x00,
    0xEA,0x00,0xC0,
    0x3E,0x91,
    0xE0,0x40,
    0x3E,0x00,
    0xE0,0x0F,
    0x3E,0x01,
    0xEA,0xFF,0xFF,
    0xFB,
    0x00,
    0x76,
    0xC3,0x68,0x01,
])
rom[0x150:0x150+len(code)]=code

checksum=0
for i in range(0x134,0x14D): checksum=(checksum-rom[i]-1)&0xFF
rom[0x14D]=checksum
g=(sum(rom)-rom[0x14E]-rom[0x14F])&0xFFFF
rom[0x14E]=(g>>8)&0xFF; rom[0x14F]=g&0xFF
out=Path(__file__).with_name('irqtest.gb')
out.write_bytes(rom)
print(f'wrote {out} {len(rom)} bytes; code={len(code)}; checksum={checksum:02X}')

#!/usr/bin/env python3
from pathlib import Path
ROM_SIZE=32768
rom=bytearray(ROM_SIZE)
logo=bytes([
0xCE,0xED,0x66,0x66,0xCC,0x0D,0x00,0x0B,0x03,0x73,0x00,0x83,0x00,0x0C,0x00,0x0D,
0x00,0x08,0x11,0x1F,0x88,0x89,0x00,0x0E,0xDC,0xCC,0x6E,0xE6,0xDD,0xDD,0xD9,0x99,
0xBB,0xBB,0x67,0x63,0x6E,0x0E,0xEC,0xCC,0xDD,0xDC,0x99,0x9F,0xBB,0xB9,0x33,0x3E])
rom[0x100:0x104]=bytes([0x00,0xC3,0x50,0x01]); rom[0x104:0x134]=logo
rom[0x134:0x13F]=b"TIMERV5\0\0\0\0"
rom[0x143]=0; rom[0x147]=0; rom[0x148]=0; rom[0x149]=0
# VBlank ISR: C001++ ; RETI
rom[0x40:0x48]=bytes([0xFA,0x01,0xC0,0x3C,0xEA,0x01,0xC0,0xD9])
# Timer ISR: C000++ ; RETI
rom[0x50:0x58]=bytes([0xFA,0x00,0xC0,0x3C,0xEA,0x00,0xC0,0xD9])
for vec in [0x48,0x58,0x60]: rom[vec]=0xD9
for vec in [0x00,0x08,0x10,0x18,0x20,0x28,0x30,0x38]: rom[vec]=0xC9
# SP; DI; clear counters; LCD on; IF=0; DIV reset; TIMA=0; TMA=0;
# TAC=enable/4096Hz; IE=VBlank|Timer; EI; NOP; HALT; JP HALT
code=bytearray([
0x31,0xFE,0xFF, 0xF3,
0x3E,0x00, 0xEA,0x00,0xC0, 0xEA,0x01,0xC0,
0x3E,0x91,0xE0,0x40,
0x3E,0x00,0xE0,0x0F,
0x3E,0x00,0xE0,0x04,
0x3E,0x00,0xE0,0x05,
0x3E,0x00,0xE0,0x06,
0x3E,0x04,0xE0,0x07,
0x3E,0x05,0xEA,0xFF,0xFF,
0xFB,0x00,
0x76,
])
halt_addr=0x150+len(code)-1
code += bytes([0xC3, halt_addr & 0xFF, halt_addr >> 8])
rom[0x150:0x150+len(code)]=code
checksum=0
for i in range(0x134,0x14D): checksum=(checksum-rom[i]-1)&0xFF
rom[0x14D]=checksum
g=(sum(rom)-rom[0x14E]-rom[0x14F])&0xFFFF
rom[0x14E]=(g>>8)&0xFF; rom[0x14F]=g&0xFF
out=Path(__file__).with_name('timertest.gb'); out.write_bytes(rom)
print(f'wrote {out} {len(rom)} bytes; code={len(code)} halt=${halt_addr:04X}')
